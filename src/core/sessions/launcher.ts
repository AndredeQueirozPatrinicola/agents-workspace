import path from 'node:path';
import { promises as fsp } from 'node:fs';
import { shellQuote } from '../../infrastructure/process/shell.js';
import { readTextIfExists, writeFileAtomic } from '../../infrastructure/filesystem/fs.js';
import type { TerminalBackend } from '../../infrastructure/terminal/backend.js';
import type { LaunchCommand } from '../../providers/types.js';

/**
 * Agent session launcher.
 *
 * Each agent session runs a small generated POSIX sh script stored in the
 * runtime directory (inside .git, never committed). The script:
 *  1. exports non-secret AW_* variables,
 *  2. runs the provider CLI in the worktree (the prompt is read from a file,
 *     so no task text is ever interpolated into shell code),
 *  3. records the exit code, then
 *  4. keeps the tmux session open with an interactive shell, so output stays
 *     visible and the agent can be restarted in place.
 */

export type SessionState = 'running' | 'exited' | 'stopped';

export interface LaunchFiles {
  dir: string;
  script: string;
  prompt: string;
  exitFile: string;
}

export function launchFilesFor(agentDir: string): LaunchFiles {
  return {
    dir: agentDir,
    script: path.join(agentDir, 'launch.sh'),
    prompt: path.join(agentDir, 'prompt.md'),
    exitFile: path.join(agentDir, 'exit-status'),
  };
}

export function renderLaunchScript(
  launch: LaunchCommand,
  meta: { agent: string; providerName: string; exitFile: string },
): string {
  const argv = [
    shellQuote(launch.command),
    ...launch.args.map((arg) => (typeof arg === 'string' ? shellQuote(arg) : `"$(cat ${shellQuote(arg.fromFile)})"`)),
  ].join(' \\\n  ');
  const exports = Object.entries(launch.env)
    .filter(([key]) => /^[A-Z_][A-Z0-9_]*$/.test(key))
    .map(([key, value]) => `export ${key}=${shellQuote(value)}`)
    .join('\n');
  const restart = `aw spawn ${meta.agent}`;
  return `#!/bin/sh
# Generated by Agent Workspace for agent "${meta.agent}".
# Machine-specific runtime file: do not edit or commit.
cd ${shellQuote(launch.cwd)} || { echo "[aw] worktree not found: ${launch.cwd.replace(/["$`\\]/g, '')}"; exec "\${SHELL:-/bin/sh}"; }
${exports}
rm -f ${shellQuote(meta.exitFile)}
printf '%s\\n' ${shellQuote(`[aw] Starting ${meta.providerName} for agent "${meta.agent}"...`)}
# Keep this wrapper alive on Ctrl-C (a handler, unlike an ignore, is reset for the agent process).
trap ':' INT
${argv}
code=$?
trap - INT
printf '%s\\n' "$code" > ${shellQuote(meta.exitFile)}
printf '\\n%s\\n%s\\n' "[aw] Agent process exited with code $code. The worktree and branch are preserved." ${shellQuote(`[aw] This shell stays open. Restart the agent from another terminal with: aw stop ${meta.agent} && ${restart}`)}
exec "\${SHELL:-/bin/sh}"
`;
}

export async function writeLaunchFiles(
  files: LaunchFiles,
  launch: LaunchCommand,
  meta: { agent: string; providerName: string },
  prompt: string | null,
): Promise<void> {
  if (prompt !== null) await writeFileAtomic(files.prompt, prompt, 0o600);
  else await fsp.rm(files.prompt, { force: true });
  await writeFileAtomic(files.script, renderLaunchScript(launch, { ...meta, exitFile: files.exitFile }), 0o700);
  await fsp.rm(files.exitFile, { force: true });
}

/** Determine whether an agent is running, has exited (shell left open), or has no session. */
export async function getSessionState(terminal: TerminalBackend, sessionName: string, exitFile: string): Promise<SessionState> {
  if (!(await terminal.hasSession(sessionName))) return 'stopped';
  const pane = await terminal.paneState(sessionName);
  if (pane?.dead) return 'exited';
  const exit = await readTextIfExists(exitFile);
  return exit === null ? 'running' : 'exited';
}

export async function readExitCode(exitFile: string): Promise<number | null> {
  const text = await readTextIfExists(exitFile);
  if (text === null) return null;
  const code = Number.parseInt(text.trim(), 10);
  return Number.isNaN(code) ? null : code;
}

/** Redact the prompt from a launch command for display and state records. */
export function describeLaunch(launch: LaunchCommand): string[] {
  return [launch.command, ...launch.args.map((a) => (typeof a === 'string' ? a : '<prompt>'))];
}
